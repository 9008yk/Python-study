# Day 1：print() 和字符串
#
# 运行方式：
#   python week01/day01.py
#
# 今天只需要理解三件事：
#   1. print() 会把括号里的内容显示到终端
#   2. 字符串就是用引号包起来的文字
#   3. 字符串可以用 + 拼接，也可以用 f-string 插入变量

print("Hello, Python!")

# 练习 1：把你的名字填进 name
name = "你的名字"
print("大家好，我是" + name)

# 练习 2：把学习目标填进 goal
goal = "掌握 Python 基础"
print(f"我今年的目标是：{goal}")

# 练习 3（挑战）：用变量拼成一句自我介绍
my_name = "你的名字"
my_hobby = "写代码"
my_goal = "做出自己的第一个项目"
print(f"我是{my_name}，喜欢{my_hobby}，{my_goal}。")

